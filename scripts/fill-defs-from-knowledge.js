function main() {
  const dataDir = path.join(__dirname, '..', 'data');
  let totalFilled = 0;

  for (const cat of ['toeic', 'toefl', 'daily']) {
    const file = path.join(dataDir, `${cat}.json`);
    const data = JSON.parse(fs.readFileSync(file, 'utf8'));
    let filled = 0;

    data.words.forEach(w => {
      if (!w.definition) {
        const def = DEFS[w.word] || DEFS[w.word.toLowerCase()];
        if (def) {
          w.definition = def;
          filled++;
        }
      }
    });

    fs.writeFileSync(file, JSON.stringify(data, null, 2));
    const stillMissing = data.words.filter(w => !w.definition).length;
    console.log(`[${cat}] filled=${filled}, still missing=${stillMissing}/${data.words.length}`);
    totalFilled += filled;
  }

  console.log(`\nTotal filled: ${totalFilled}`);
}

main();
